import type { ProductCardInput } from "@/types/product-card";
import { buildEditInstructionsBlock } from "@/lib/series/editing";

function buildProductContextBlock(input: ProductCardInput & { category: string }) {
  const lines = [
    `Описание товара (факты): ${input.productDescription}`,
    `Категория: ${input.category}`
  ];

  if (input.identifiedProductName) {
    lines.push(`Определено по фото: ${input.identifiedProductName}`);
  }

  if (input.sellerWishes?.trim()) {
    lines.push(
      `Пожелания продавца к карточке: ${input.sellerWishes.trim()}`,
      "ВАЖНО: пожелания продавца — это акценты, визуальные идеи или сценарий подачи. Они НЕ меняют тип товара.",
      "Если пожелания звучат метафорично или шутливо, интерпретируй их только в рамках реального товара с фото."
    );
  }

  return lines.join("\n");
}

export function buildCardPrompt(input: ProductCardInput & { category: string }) {
  const editBlock = buildEditInstructionsBlock(input.editInstructions, input.previousCard);
  const role = getMarketplaceRole(input.marketplace);
  const audience = getAudienceHint(input.category);
  const textRules = getMarketplaceTextRules(input.marketplace);
  const visualRules = getVisualRules(input.style, input.marketplace);

  return `${role}
Ты готовишь одну полноценную карточку товара для публикации на маркетплейсе: заголовок, описание, буллеты, характеристики, SEO, тексты для первого слайда и визуальную концепцию.
Работай как селлер и редактор карточек: конкретика важнее красивых общих слов.
Не придумывай свойства, которых нет во входных данных. Если материал, размер, объем, комплектация или цвет неизвестны, формулируй нейтрально.
Не используй медицинские, юридические, гарантированные или запрещенные обещания.
Верни только валидный JSON без markdown.

Входные данные:
${buildProductContextBlock(input)}
Маркетплейс: ${input.marketplace}
Стиль карточки: ${input.style}
Предполагаемая аудитория: ${audience}
Добавить SEO-ключи: ${input.includeSeo ? "да" : "нет"}
Сделать акцент на выгодах: ${input.focusBenefits ? "да" : "нет"}
Подготовить текст для инфографики: ${input.includeInfographicText ? "да" : "нет"}
Имя файла изображения: ${input.imageFileName || "не указано"}

Правила для текста:
${textRules}
- Заголовок должен быть названием товара для маркетплейса, а не фразой про генератор или сервис.
- В заголовке органично используй 1-2 поисковые фразы и 1-2 факта из входного описания, если они есть.
- Описание: пользователь должен получить только готовый продающий контент про сам товар. Не объясняй, как текст создан, куда он подходит и почему он безопасный.
- Никогда не пиши служебные фразы: "нейтральное описание", "без рекламных обещаний", "для карточки Wildberries", "текст для маркетплейса", "польза сформулирована", "товар для маркетплейса".
- Буллеты benefits: 5 пунктов, каждый до 12 слов, только свойства, выгоды, комплектация, сценарии или ощущения от самого товара. Не пиши про качество генерации, дизайна, карточки, текста, SEO или подачи.
- Характеристики: 5-7 пунктов, только факты из описания или нейтральные поля "Назначение", "Категория", "Сценарий".
- SEO-ключи: 8-15 фраз, только реальные поисковые запросы покупателя по товару и категории. Не добавляй "товар", "товары для маркетплейса", "маркетплейс", "Wildberries", "Ozon", "WB", "Avito", "Яндекс Маркет", если это не часть названия самого товара.
- Стоп-слова и клише не использовать: лучший, топ, хит, эксклюзивный, идеальный, революционный, незаменимый, высокое качество, не пожалеете.

Правила для визуальной карточки:
${visualRules}
- visualConcept должен описывать готовую картинку 1:1 для первого фото карточки: композиция, фон, место товара, 2-3 текстовых акцента.
- infographicTexts: 4 короткие фразы до 18 символов для плашек на первом слайде.
- Если загружено фото, визуальная карточка должна использовать именно его как главный товар, без случайных товаров.

JSON должен быть такого вида:
{
  "title": "string",
  "shortDescription": "string",
  "fullDescription": "string",
  "benefits": ["string"],
  "characteristics": [{"key":"string","value":"string"}],
  "keywords": ["string"],
  "infographicTexts": ["string"],
  "marketplaceTips": ["string"],
  "visualConcept": "string"
}

Требования:
- title до 120 символов
- shortDescription 1-2 предложения
- fullDescription 650-950 символов
- benefits 5 пунктов
- characteristics 5-7 пунктов
- keywords 8-15 слов или фраз, если SEO включено; иначе 5-8 базовых фраз
- infographicTexts 4 короткие фразы до 18 символов каждая
- marketplaceTips 3 рекомендации
- Товар из описания должен явно влиять на результат.
- Никаких вступлений, пояснений, markdown и комментариев вне JSON.${editBlock}`;
}

function getMarketplaceRole(marketplace: string) {
  if (marketplace === "Wildberries") {
    return "Роль: ты опытный селлер на Wildberries и SEO-копирайтер, пишешь без воды и переспама.";
  }

  if (marketplace === "Ozon") {
    return "Роль: ты старший контент-менеджер Ozon, готовишь карточку под ключ для каталога и рекламы.";
  }

  if (marketplace === "Яндекс Маркет") {
    return "Роль: ты SEO-специалист Яндекс Маркета, пишешь нейтрально, точно и каталожно.";
  }

  if (marketplace === "Avito") {
    return "Роль: ты performance-копирайтер Avito, делаешь понятное объявление с акцентом на сценарий и выгоду.";
  }

  return "Роль: ты маркетолог маркетплейсов и копирайтер карточек товара.";
}

function getMarketplaceTextRules(marketplace: string) {
  if (marketplace === "Wildberries") {
    return "- Для Wildberries делай плотный заголовок и короткие акценты для первого фото.\n- Ключи вписывай естественно, без повторения одного слова подряд.";
  }

  if (marketplace === "Ozon") {
    return "- Для Ozon делай описание из 2-3 коротких абзацев.\n- Буллеты должны помогать сравнить товар по назначению, комплектации и сценарию.";
  }

  if (marketplace === "Яндекс Маркет") {
    return "- Для Яндекс Маркета избегай рекламного давления.\n- Характеристики формулируй как нейтральные каталожные факты.";
  }

  if (marketplace === "Avito") {
    return "- Для Avito подчеркни состояние, назначение и понятную пользу.\n- Тон живой, но без агрессивных продаж.";
  }

  return "- Тон уверенный, конкретный, без клише.\n- Текст должен быть готов к ручной публикации после проверки продавцом.";
}

function getVisualRules(style: string, marketplace: string) {
  const base = `- Формат изображения: 1:1, как первое фото карточки на ${marketplace}.\n- Товар занимает 60-75% кадра, расположен крупно и читаемо.\n- Текст на картинке короткий, крупный, кириллица, без мелких длинных абзацев.`;

  if (style === "Минималистичный") {
    return `${base}\n- Светлый нейтральный фон, много воздуха, 2-3 аккуратные выноски.`;
  }

  if (style === "Премиальный") {
    return `${base}\n- Темный или молочный премиальный фон, один сильный акцент, без скидочного шума.`;
  }

  if (style === "Яркий") {
    return `${base}\n- Контрастный рекламный фон, крупный оффер и заметные плашки, но без перегруза.`;
  }

  if (style === "Нежный") {
    return `${base}\n- Пастельный фон, мягкий свет, плавные формы, спокойные подписи.`;
  }

  if (style === "Технологичный") {
    return `${base}\n- Темный SaaS/cyber-фон, голубые акценты, сетка и короткие технические плашки.`;
  }

  return base;
}

function getAudienceHint(category: string) {
  if (category.includes("Электроника")) {
    return "покупатели, которые сравнивают функции, совместимость и пользу в повседневном использовании";
  }

  if (category.includes("Декор")) {
    return "люди, которые выбирают акцент для интерьера, рабочего стола или подарка";
  }

  if (category.includes("Красота")) {
    return "покупатели, которые ищут понятный уход без неподтвержденных обещаний";
  }

  if (category.includes("Дет")) {
    return "родители и покупатели подарков, которым важны назначение и удобство";
  }

  if (category.includes("Кухня")) {
    return "покупатели, которые выбирают практичный товар для дома и ежедневного использования";
  }

  return "покупатели маркетплейса, которые быстро оценивают товар по фото, названию и первым выгодам";
}
